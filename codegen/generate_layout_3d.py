#!/usr/bin/env python3
"""The by-links-3d layout's shared files -> addons/onlyworlds/ow_layout_directions.gd (the directions table
OWLayout.layout_by_links_3d reads) and tests/data/layout-by-links-3d.bits.json (the method fixture's numbers as bits, for
tests/test_layout_by_links_3d.gd).

The method packs a body's parts apart in directions read from a table, never computed (the default layouts page,
profiles/layout.md, its directions paragraph): for each K from 1 to 37, K unit vectors [x, y, z], flat, K = 1 first; the
vectors of K start at vector K * (K - 1) / 2, so at index 3 * K * (K - 1) / 2 of the flat list. Read here from the pinned
dist's own copy (codegen/schema-dist/profiles/layout-by-links-3d.directions.json, whose sha256 the fixture names as
table_sha256; Python's json reads a decimal exactly, and a `-0.0` as -0). The table is the vectors' bit patterns as signed
64-bit integers, as ow_layout_anchors.gd holds the by-kind anchors, which OWLayout turns into floats byte for byte.

The bits file holds, for each case of profiles/layout-by-links-3d.fixture.json, every number of its input that is not a
whole number, as a path into the input and 16 hex digits (big-endian), and its want's points as 16 hex digits each:
Godot's JSON parser reads some 17-digit decimals as a neighbouring double, so a held point or a wanted coordinate cannot
pass through it. Whole numbers (ids' Pin x and y, a held point rounded to whole numbers) parse exactly and are left to
the fixture. It names both files' sha256.

    python codegen/generate_layout_3d.py           write both
    python codegen/generate_layout_3d.py --check   exit 1 if either is stale

Both are written LF-only, as the repo's .gitattributes keeps them.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROFILES = ROOT / "codegen" / "schema-dist" / "profiles"
FIXTURE = PROFILES / "layout-by-links-3d.fixture.json"
TABLE_JSON = PROFILES / "layout-by-links-3d.directions.json"
TABLE = ROOT / "addons" / "onlyworlds" / "ow_layout_directions.gd"
BITS = ROOT / "tests" / "data" / "layout-by-links-3d.bits.json"


def hexbits(v: float) -> str:
    return struct.pack(">d", float(v)).hex()


def signed(v: float) -> int:
    return struct.unpack("<q", struct.pack("<d", v))[0]


def flat_directions(doc: dict) -> tuple[int, list[float]]:
    k_max = doc["k_max"]
    table = doc["directions"]
    if sorted(table, key=int) != [str(k) for k in range(1, k_max + 1)]:
        raise ValueError(f"the directions table holds K = 1 to {k_max}, each once")
    flat: list[float] = []
    for k in range(1, k_max + 1):
        row = table[str(k)]
        if not isinstance(row, list) or len(row) != k:
            raise ValueError(f"K = {k} does not hold {k} vectors")
        for p in row:
            if not isinstance(p, list) or len(p) != 3 or not all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in p):
                raise ValueError(f"K = {k} holds a vector that is not [x, y, z]")
            flat += [float(v) for v in p]
    return k_max, flat


def floats_in(value, path: list) -> list:
    """Every float (not an int, not a bool) under value, as [path, hex], in document order."""
    out = []
    if isinstance(value, bool) or isinstance(value, int) or value is None or isinstance(value, str):
        return out
    if isinstance(value, float):
        return [[path, hexbits(value)]]
    if isinstance(value, list):
        for i, v in enumerate(value):
            out += floats_in(v, path + [i])
    elif isinstance(value, dict):
        for k, v in value.items():
            out += floats_in(v, path + [k])
    return out


def render() -> tuple[str, str]:
    table_bytes = TABLE_JSON.read_bytes()
    table_sha = hashlib.sha256(table_bytes).hexdigest()
    k_max, flat = flat_directions(json.loads(table_bytes.decode("utf-8")))
    fixture_bytes = FIXTURE.read_bytes()
    fixture_sha = hashlib.sha256(fixture_bytes).hexdigest()
    fx = json.loads(fixture_bytes.decode("utf-8"))
    if fx["table_sha256"] != table_sha:
        raise ValueError("the fixture's table_sha256 is not the directions table's sha256")

    lines = [
        f"# GENERATED by codegen/generate_layout_3d.py from codegen/schema-dist/profiles/layout-by-links-3d.directions.json (sha256 {table_sha}). Do not edit: regenerate.",
        "class_name OWLayoutDirections",
        "extends RefCounted",
        "## The by-links-3d layout's directions: for each count of parts K from 1 to 37, the K unit vectors (x, y, z) a",
        "## body's parts are packed apart in, flat, K = 1 first; the vectors of K start at index 3 * K * (K - 1) / 2. Each is",
        "## a float64's bit pattern as a signed 64-bit integer, never a decimal: Godot's own parser reads some 17-digit",
        "## decimals as a neighbouring double. A -0.0 of the table is kept as its own bits.",
        "",
        f'const TABLE_SHA256 := "{table_sha}"',
        f"const K_MAX := {k_max}",
        "",
        "const BITS := [",
    ]
    for i in range(0, len(flat), 3):
        x, y, z = flat[i], flat[i + 1], flat[i + 2]
        lines.append(f"\t{signed(x)}, {signed(y)}, {signed(z)},  # {x!r}, {y!r}, {z!r}")
    lines += ["]", ""]
    table = "\n".join(lines)

    cases = {}
    for c in fx["cases"]:
        if c["name"] in cases:
            raise ValueError(f"two cases are named {c['name']}")
        want = c["want"]
        cases[c["name"]] = {
            "floats": floats_in(c["input"], []),
            "points": [hexbits(v) for v in want.get("points", [])],
        }
    bits = {
        "fixture_sha256": fixture_sha,
        "table_sha256": table_sha,
        "directions": [hexbits(v) for v in flat],
        "cases": cases,
    }
    return table, json.dumps(bits, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if either output is stale")
    args = parser.parse_args()
    table, bits = render()
    outs = [(TABLE, table), (BITS, bits)]
    if args.check:
        stale = [p for p, text in outs if not p.exists() or p.read_bytes().decode("utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run python codegen/generate_layout_3d.py)", file=sys.stderr)
        if not stale:
            print("ok: the directions table and the bits file match codegen/schema-dist/profiles/layout-by-links-3d.*.json")
        return 1 if stale else 0
    for p, text in outs:
        p.write_bytes(text.encode("utf-8"))
        print(f"wrote {p.relative_to(ROOT)} ({len(text.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
