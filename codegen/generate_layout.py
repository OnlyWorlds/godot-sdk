#!/usr/bin/env python3
"""The shared layout fixture -> addons/onlyworlds/ow_layout_anchors.gd (the anchor table OWLayout.layout_by_kind reads)
and tests/data/layout.bits.json (the fixture's wants as bits, for tests/test_layout.gd).

layout_by_kind starts each kind of element at a point on a circle and pulls it back there. The method is chaotic: one
anchor one unit in the last place off moves a large world's picture by a tenth of its frame. Cosine and sine are not
correctly rounded and differ between runtimes, so the anchors are never computed at run time: they are one table of
253 points (for k kinds, k = 1 to 22, the k points, flat, the points of k from index k * (k - 1)), the same float64
values the npm SDK and the Python package hold, read here from the shared fixture, the pinned dist's own
(codegen/schema-dist/profiles/layout.fixture.json since serial 132, its `anchors`; Python's json reads a decimal
exactly). Its `unplaced` suite is not read: the package has no unplaced reader.

Both outputs hold bits, never decimals: Godot's JSON parser reads some 17-digit decimals as a neighbouring double
(measured on this fixture with Godot 4.7.2: 56 of its 506 anchors and 871 of its 6,464 wanted coordinates), so neither
the table nor the wants can pass through it, and a GDScript float literal is not trusted either. The table is the
anchors' bit patterns as signed 64-bit integers, which OWLayout turns into floats byte for byte; the bits file holds
each wanted coordinate as 16 hex digits (big-endian), keyed by case name, and names the fixture's sha256.

    python codegen/generate_layout.py           write both
    python codegen/generate_layout.py --check   exit 1 if either is stale

Both are written LF-only, as the repo's .gitattributes keeps them.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "codegen" / "schema-dist" / "profiles" / "layout.fixture.json"
TABLE = ROOT / "addons" / "onlyworlds" / "ow_layout_anchors.gd"
BITS = ROOT / "tests" / "data" / "layout.bits.json"
KINDS = 22


def flat_anchors(table: dict) -> list[float]:
    if sorted(table, key=int) != [str(k) for k in range(1, KINDS + 1)]:
        raise ValueError(f"the anchor table holds k = 1 to {KINDS}, each once")
    flat: list[float] = []
    for k in range(1, KINDS + 1):
        row = table[str(k)]
        if not isinstance(row, list) or len(row) != k:
            raise ValueError(f"k = {k} does not hold {k} points")
        for p in row:
            if not isinstance(p, list) or len(p) != 2 or not all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in p):
                raise ValueError(f"k = {k} holds a point that is not [x, y]")
            flat += [float(p[0]), float(p[1])]
    return flat


def hexbits(v: float) -> str:
    return struct.pack(">d", float(v)).hex()


def render() -> tuple[str, str]:
    data = FIXTURE.read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    fx = json.loads(data.decode("utf-8"))
    flat = flat_anchors(fx["anchors"])
    lines = [
        f"# GENERATED by codegen/generate_layout.py from codegen/schema-dist/profiles/layout.fixture.json (sha256 {sha}), its anchors. Do not edit: regenerate.",
        "class_name OWLayoutAnchors",
        "extends RefCounted",
        "## The by-kind layout's anchors: for each count of kinds k from 1 to 22, the k points (x, y) on the unit circle where",
        "## the kinds sit, flat, k = 1 first; the points of k start at index k * (k - 1). Each is a float64's bit pattern as a",
        "## signed 64-bit integer, never a decimal: Godot's own parser reads some 17-digit decimals as a neighbouring double.",
        "",
        f'const FIXTURE_SHA256 := "{sha}"',
        "",
        "const BITS := [",
    ]
    for i in range(0, len(flat), 2):
        x, y = flat[i], flat[i + 1]
        bx = struct.unpack("<q", struct.pack("<d", x))[0]
        by = struct.unpack("<q", struct.pack("<d", y))[0]
        lines.append(f"\t{bx}, {by},  # {x!r}, {y!r}")
    lines += ["]", ""]
    table = "\n".join(lines)

    bits = {
        "fixture_sha256": sha,
        "anchors": [hexbits(v) for v in flat],
        "cases": {c["name"]: [[hexbits(w[0]), hexbits(w[1])] for w in c["want"]] for c in fx["cases"]},
        "around": {c["name"]: [[hexbits(w[2]), hexbits(w[3])] for w in c["want"]] for c in fx["around"]},
    }
    return table, json.dumps(bits, indent=1) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if either output is stale")
    args = parser.parse_args()
    table, bits = render()
    outs = [(TABLE, table), (BITS, bits)]
    if args.check:
        stale = [p for p, text in outs if not p.exists() or p.read_bytes().decode("utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run python codegen/generate_layout.py)", file=sys.stderr)
        if not stale:
            print("ok: the anchor table and the bits file match codegen/schema-dist/profiles/layout.fixture.json")
        return 1 if stale else 0
    for p, text in outs:
        p.write_bytes(text.encode("utf-8"))
        print(f"wrote {p.relative_to(ROOT)} ({len(text.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
